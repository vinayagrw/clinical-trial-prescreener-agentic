/*
 * Insights + ambient + cohort types — M2 and M3 capabilities.
 *
 * These power the /insights page (what-if, safety correlation, cohort patterns)
 * and the AmbientInsightsRail on the cockpit.
 */

export interface WhatIfScenario {
  id: string;
  label: string;
  changedCriterion: { id: string; newThreshold: string };
  cohortDelta: {
    before: number;
    after: number;
    newlyEligiblePatientIds: string[];
  };
}

export interface CohortPattern {
  id: string;
  title: string;
  sharedBlockerCriterionId: string;
  affectedMatchIds: string[];
  suggestedAction: string;
}

export interface SafetySignal {
  id: string;
  trialIds: string[];
  signalType: "ae_cluster" | "sae_correlation" | "missing_safety_visit";
  severity: "low" | "medium" | "high";
  detail: string;
}

/**
 * Ambient insight — proactively generated by the agent, not in response to a question.
 * The frequencyCapKey is used by memory.ts to prevent re-surfacing a dismissed insight
 * until a cooldown elapses.
 */
export interface AmbientInsight {
  id: string;
  generatedAt: string;
  scope: "queue" | "review" | "insights";
  title: string;
  body: string;
  suggestedActionLabel?: string;
  suggestedActionHref?: string;
  dismissible: true;
  frequencyCapKey: string;
}
